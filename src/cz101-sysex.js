function buildTable(rows) { return Object.fromEntries(rows.map(([k,...v]) => [k,v])); }
function clamp(n,min,max){ return Math.max(min,Math.min(max,Number(n)||0)); }
function startsWith(data,prefix){ return prefix.every((v,i)=>data[i]===v); }
function hex(data){ return Array.from(data).map(v=>v.toString(16).padStart(2,'0').toUpperCase()).join(' '); }
