/*
 * Casio CZ-101 tone encoder + Web MIDI handshake.
 *
 * Logical tone format: 128 bytes, transmitted low-nibble then high-nibble,
 * resulting in 256 7-bit-safe data bytes.
 *
 * IMPORTANT: this module is intentionally isolated. Before relying on it for
 * archival work, compare generated messages against known-good CZ-101 dumps.
 */

const DCA_KF = [0x00,0x08,0x11,0x1A,0x24,0x2F,0x3A,0x45,0x52,0x5F];
const DCW_KF = [0x00,0x1F,0x2C,0x39,0x46,0x53,0x60,0x6E,0x92,0xFF];
const VIB_WAVE = {1:0x08, 2:0x04, 3:0x20, 4:0x02};

export function encodeTone(patch) {
  const b = [];
  b.push(encodePflag(patch.common));
  b.push(patch.common.detune.direction === 'down' ? 1 : 0);
  b.push(encodeFine(patch.common.detune.fine));
  b.push(clamp(patch.common.detune.octave,0,3) * 12 + clamp(patch.common.detune.note,0,11));
  b.push(VIB_WAVE[patch.common.vibrato.wave] ?? VIB_WAVE[1]);
  b.push(...encodeVibDelay(patch.common.vibrato.delay));
  b.push(...encodeVibRate(patch.common.vibrato.rate));
  b.push(...encodeVibDepth(patch.common.vibrato.depth));
  b.push(...encodeLine(patch.line1, true));
  b.push(...encodeLine(patch.line2, false));
  if (b.length !== 128) throw new Error(`Internal codec error: expected 128 tone bytes, got ${b.length}`);
  return Uint8Array.from(b.map(v => v & 0xFF));
}

export function nibblize(bytes) {
  const out = [];
  for (const v of bytes) out.push(v & 0x0F, (v >> 4) & 0x0F);
  return Uint8Array.from(out);
}

export function buildCompletePatchMessage(channel0, patch, program = 0x60) {
  const data = nibblize(encodeTone(patch));
  // Web MIDI only accepts complete SysEx messages in a send() call.  The
  // original CZ protocol documentation describes an interactive transfer in
  // which F0 ... header, ACKs, payload and F7 are exchanged as a stream. That
  // cannot be represented by MIDIOutput.send(), because Chrome rejects a SysEx
  // fragment that starts with F0 and does not end with F7.
  //
  // Standard CZ .syx files use this complete-message representation:
  // F0 44 00 00 7n 20 pp <256 nibble bytes> F7
  // where pp is the target program (60 = temporary/current sound).
  return Uint8Array.from([
    0xF0, 0x44, 0x00, 0x00, 0x70 + channel0, 0x20, program,
    ...data,
    0xF7
  ]);
}

export function buildSysexSmokeTest(channel0) {
  // A complete, syntactically valid CZ SysEx command. Tone Mix OFF is used
  // only to verify that Chrome/Web MIDI can transmit a framed Casio message.
  return Uint8Array.from([0xF0,0x44,0x00,0x00,0x70 + channel0,0x42,0x00,0xF7]);
}

export async function testCZSysex({ midiOutput, channel = 1, log = ()=>{} }) {
  if (!midiOutput) throw new Error('Choose a MIDI output');
  const channel0 = clamp(channel - 1, 0, 15);
  const msg = buildSysexSmokeTest(channel0);
  log(`TX complete SysEx smoke test: ${hex(msg)}`);
  midiOutput.send(msg);
  log('Web MIDI accepted the complete SysEx frame');
  return msg;
}

export async function sendPatchToCZ({ midiOutput, channel = 1, patch, program = 0x60, log = ()=>{} }) {
  if (!midiOutput) throw new Error('Choose a MIDI output');
  const channel0 = clamp(channel - 1, 0, 15);
  const msg = buildCompletePatchMessage(channel0, patch, program);
  log(`TX complete CZ patch SysEx: ${msg.length} bytes`);
  log(`TX head: ${hex(msg.slice(0,24))} …`);
  log(`TX tail: … ${hex(msg.slice(-16))}`);
  midiOutput.send(msg);
  log(`Patch frame sent to ${program === 0x60 ? 'temporary/current sound' : 'program 0x' + program.toString(16).toUpperCase()}`);
}

function encodePflag(common) {
  const ls = { line1:0, line2:1, 'line1+line1':2, 'line1+line2':3 }[common.lineSelect] ?? 0;
  const oct = common.octave === 1 ? 1 : common.octave === -1 ? 2 : 0;
  return (oct << 2) | ls;
}

function encodeFine(fine) {
  fine = clamp(fine,0,60);
  if (fine <= 15) return fine;
  if (fine <= 30) return fine + 1;
  if (fine <= 45) return fine + 2;
  return fine + 3;
}

function encodeVibDelay(v) {
  v = clamp(v,0,99);
  if (v <= 31) return [v,0,v];
  // Derived from the documented table: byte3 grows in powers-of-two regions.
  const table = VIB_DELAY[v];
  if (!table) throw new Error(`Unsupported vibrato delay ${v}`);
  return table;
}

function encodeVibRate(v) {
  v = clamp(v,0,99);
  if (v <= 24) {
    // Documented sequence starts 00 00 20, 01 00 40 … 06 00 E0, 07 01 00.
    const units = (v + 1) * 0x20;
    return [v, (units >> 8) & 0xFF, units & 0xFF];
  }
  const table = VIB_RATE[v];
  if (!table) throw new Error(`Unsupported vibrato rate ${v}`);
  return table;
}

function encodeVibDepth(v) {
  v = clamp(v,0,99);
  if (v <= 31) return [v,0,v + 1];
  const table = VIB_DEPTH[v];
  if (!table) throw new Error(`Unsupported vibrato depth ${v}`);
  return table;
}

function encodeLine(line, firstLine) {
  const out = [];
  out.push(...encodeWave(line.waveform1, line.waveform2, firstLine ? line.modulation : 'none'));
  out.push(clamp(line.dcaKeyFollow,0,9), DCA_KF[clamp(line.dcaKeyFollow,0,9)]);
  out.push(clamp(line.dcwKeyFollow,0,9), DCW_KF[clamp(line.dcwKeyFollow,0,9)]);
  out.push(...encodeEnvelope(line.envelopes.dca, 'dca'));
  out.push(...encodeEnvelope(line.envelopes.dcw, 'dcw'));
  out.push(...encodeEnvelope(line.envelopes.dco, 'dco'));
  return out;
}

function encodeWave(w1, w2, modulation) {
  const [a1,a2] = waveBits(clamp(w1,1,8), false);
  const [b1,b2] = waveBits(clamp(w2,0,8), true);
  let word = (a1 << 8) | a2;
  word |= (b1 << 8) | b2;
  const mod = modulation === 'ring' ? 0b100 : modulation === 'noise' ? 0b011 : 0;
  word |= mod << 3;
  return [(word >> 8) & 0xFF, word & 0xFF];
}

function waveBits(n, second) {
  if (!n) return [0,0];
  const code = n <= 5 ? [0,1,2,4,5][n-1] : 6;
  const tail = n <= 5 ? 0 : n - 5;
  // First waveform occupies bits 15..13. Second uses bits 12..10 plus flag bit 9.
  if (!second) return [(code << 5), tail];
  return [((code << 2) | 0x02), tail];
}

function encodeEnvelope(env, kind) {
  const out = [clamp(env.endStep,1,8) - 1];
  for (let i=0;i<8;i++) {
    const s = env.steps[i] || {rate:0,level:0,sustain:false};
    const previousLevel = i === 0 ? 0 : (env.steps[i-1]?.level ?? 0);
    const descending = s.level < previousLevel;
    let r, l;
    if (kind === 'dca') {
      r = Math.floor(119 * clamp(s.rate,0,99) / 99);
      l = Math.floor(127 * clamp(s.level,0,99) / 99);
    } else if (kind === 'dcw') {
      // Documentation names this as the DCW rate conversion despite a likely
      // wording typo around "level"; preserve the published numeric mapping.
      r = Math.floor(119 * clamp(s.rate,0,99) / 99) + 8;
      l = Math.floor(127 * clamp(s.level,0,99) / 99);
    } else {
      r = Math.floor(127 * clamp(s.rate,0,99) / 99);
      const lv = clamp(s.level,0,99);
      l = lv <= 63 ? lv : lv + 4;
    }
    if (descending) r |= 0x80;
    // Sustain is encoded in the high bit of the level byte for CZ envelopes.
    // This is explicitly documented for DCW and is used consistently here;
    // verify with golden dumps before archival use.
    if (s.sustain) l |= 0x80;
    out.push(r & 0xFF, l & 0xFF);
  }
  return out;
}

